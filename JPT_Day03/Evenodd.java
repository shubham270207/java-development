package JPT_Day03;

public class Evenodd {
    public static void main(String arg[]){
        for(int num=1; num<=1000; num++){
            if(num%2==0){
                System.out.println(num +"  Number is Even");
            }
            else{
                System.out.println(num +"  Number is Odd");
            }
        }
    }
    
}
