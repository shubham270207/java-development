public class Average {
    public static void main(String arg[]){
        int num1 = 10;
        int num2 = 44;
        int num3 = 53;

        int total = num1 + num2 + num3;
        System.out.println("Total=" + total);

        double avg = total / 3.0;
        System.out.println("Average=" + avg);
    }
}
